update education
set education_visible = institution_id in (
    select institution_id
    from institution
    where lower(trim(institution_name)) in (
              'universidad tecnológica israel',
              'universidad tecnologica israel',
              'escuela politécnica nacional',
              'escuela politecnica nacional'
          )
       or lower(trim(institution_name_es)) in (
              'universidad tecnológica israel',
              'universidad tecnologica israel',
              'escuela politécnica nacional',
              'escuela politecnica nacional'
          )
);

update skill
set skill_category = case
    when lower(skill_name) in (
        'angular', 'typescript', 'rxjs', 'javascript', 'angular material',
        'primeng', 'bootstrap', 'tailwind', 'html', 'css'
    ) then 'FRONTEND'
    when lower(skill_name) in (
        'java', 'spring boot', 'laravel', 'php', 'rest api', 'rest apis',
        'spring security', 'jpa', 'hibernate', 'jpa / hibernate'
    ) then 'BACKEND'
    when lower(skill_name) in (
        'oracle', 'oracle database', 'postgresql', 'mysql', 'sql server'
    ) then 'DATABASE'
    when lower(skill_name) in (
        'docker', 'ci/cd', 'git', 'github', 'github actions',
        'oracle visual builder studio', 'aws', 'linux', 'nginx'
    ) then 'DEVOPS_CLOUD'
    when lower(skill_name) in (
        'junit', 'mockito', 'phpunit', 'mockery', 'angular testbed',
        'vitest', 'playwright', 'unit testing', 'integration testing', 'e2e testing'
    ) then 'TESTING'
    when lower(skill_name) in (
        'hexagonal architecture', 'arquitectura hexagonal',
        'domain-driven design', 'domain-driven design (ddd)', 'ddd',
        'layered architecture', 'arquitectura por capas', 'mvc',
        'solid', 'clean code', 'modular design', 'diseño modular'
    ) then 'ARCHITECTURE'
    else 'OTHER'
end;
