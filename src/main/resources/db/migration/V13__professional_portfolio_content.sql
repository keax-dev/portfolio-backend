alter table skill
    add column skill_category varchar(40) not null default 'OTHER';

alter table skill
    add column skill_visible boolean not null default true;

alter table skill
    add constraint chk_skill_category
        check (skill_category in (
            'FRONTEND',
            'BACKEND',
            'DATABASE',
            'DEVOPS_CLOUD',
            'TESTING',
            'ARCHITECTURE',
            'OTHER'
        ));

alter table education
    add column education_visible boolean not null default true;

alter table course
    add column course_visible boolean not null default true;

create table experience (
    experience_id bigint generated by default as identity primary key,
    experience_role varchar(160) not null,
    experience_role_es varchar(160) not null,
    experience_company varchar(160) not null,
    experience_description text not null,
    experience_description_es text not null,
    experience_start varchar(80) not null,
    experience_start_es varchar(80) not null,
    experience_end varchar(80),
    experience_end_es varchar(80),
    experience_position integer not null,
    experience_visible boolean not null default true,
    experience_deleted boolean not null default false,
    version bigint not null default 0,
    constraint chk_experience_position_positive check (experience_position > 0)
);

create index idx_skill_deleted_visible_category_position
    on skill (skill_deleted, skill_visible, skill_category, skill_position);

create index idx_education_deleted_visible_position
    on education (education_deleted, education_visible, education_position);

create index idx_course_deleted_visible_position
    on course (course_deleted, course_visible, course_position);

create index idx_experience_deleted_position
    on experience (experience_deleted, experience_position);

create index idx_experience_deleted_visible_position
    on experience (experience_deleted, experience_visible, experience_position);

